/** Rename players in a (loaded) game to their known names. Returns how many changed. */
export function applyKnownNames(players: Record<number, { name: string }>): number {
  let n = 0;
  for (const id in players) {
    const to = KNOWN_AS[players[id].name];
    if (to) {
      players[id].name = to;
      n++;
    }
  }
  return n;
}
